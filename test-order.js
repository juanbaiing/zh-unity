const { 生成中文 } = require('./canvas.js');

// 复刻用户截图里的画布：字段在上，新建变量/变量运算在下
const 表 = new Map();
function 加(id, 类型, x, y, 父, 后, 内容 = {}) {
  表.set(id, { id, 类型, x, y, 父, 后, ...内容 });
}

加(1, '类', 40, 30, null, null, { 名: '敌人', 继承: 'MonoBehaviour' });

// 画布上的实际位置：字段在上方，语句在下方
加(2, '字段', 110, 200, 1, 3, { 数据类型: '整数', 名: '血量', 值: '30' });
加(3, '字段', 110, 300, 1, null, { 数据类型: '整数', 名: '分', 值: '10' });

加(4, '新建变量', 100, 400, 1, 5, { 名: '变量', 值: '0' });
加(5, '变量运算', 100, 480, 1, null, { 名: '变量', 运算法: '加', 值: '2' });

console.log('画布顺序（从上到下）：血量(200) → 分(300) → 新建变量(400) → 变量运算(480)');
console.log('连线：血量 → 分，新建变量 → 变量运算\n');

console.log('=== 生成的顺序 ===');
