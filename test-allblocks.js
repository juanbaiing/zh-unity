// 新块全家桶的端到端测试：块树 → 中文 → C# → 编译
const { 新块, 生成中文, 生成CSharp } = require('./blocks.js');
const fs = require('fs');
const path = require('path');

const 类 = 新块('类'); 类.名 = '敌人'; 类.继承 = 'MonoBehaviour';

const 血 = 新块('字段'); 血.数据类型 = '整数'; 血.名 = '血量'; 血.值 = '30';
const 计时 = 新块('字段'); 计时.数据类型 = '小数'; 计时.名 = '计时'; 计时.值 = '0';
const 目 = 新块('字段'); 目.数据类型 = '物体'; 目.名 = '目标'; 目.值 = '';

const 开始 = 新块('方法'); 开始.名 = '开始时';
const 打 = 新块('打印'); 打.值 = '"开始"';
const 局部 = 新块('局部变量'); 局部.名 = '计数'; 局部.值 = '0';
const 加 = 新块('加一'); 加.名 = '计数';
const 警 = 新块('警告'); 警.值 = '"注意"';
const 设 = 新块('设若'); 设.条件 = '血量 小于等于 0';
const 销毁块 = 新块('销毁'); 销毁块.目标 = '自己'; 销毁块.延时 = '1';
const 否则块 = 新块('否则');
const 减 = 新块('减一'); 减.名 = '血量';
const 打印2 = 新块('打印'); 打印2.值 = '"活着"';
设.子.push(销毁块);
否则块.子.push(减, 打印2);
开始.子.push(打, 局部, 加, 警, 设, 否则块);

const 更新 = 新块('方法'); 更新.名 = '更新时';
const 局部名单 = 新块('局部变量'); 局部名单.名 = '名单'; 局部名单.值 = '新建列表（整数）';
const 遍历 = 新块('遍历'); 遍历.列表 = '名单'; 遍历.元素 = '名字';
const 打印3 = 新块('打印'); 打印3.值 = '名字';
const 设若2 = 新块('设若'); 设若2.条件 = '名字 等于 3';
const 跳出块 = 新块('跳出');
设若2.子.push(跳出块);
遍历.子.push(打印3, 设若2);

const 清 = 新块('清空'); 清.列表 = '名单';
更新.子.push(局部名单, 遍历, 清);

const 重新 = 新块('方法'); 重新.名 = '重置'; 重新.公开 = true;
const 激活 = 新块('设置激活'); 激活.对象 = '目标'; 激活.开 = '假';
重新.子.push(激活);

类.子.push(血, 计时, 目, 开始, 更新, 重新);

const 中文 = 生成中文([类]);
const CSharp = 生成CSharp([类]);

console.log('=== 中文套式 ===');
console.log(中文);
console.log('\n=== 生成的 C# ===');
console.log(CSharp);

fs.writeFileSync(path.join(__dirname, 'unitycheck', '敌人.cs'), CSharp, 'utf8');
console.log('已写入 unitycheck/敌人.cs');
