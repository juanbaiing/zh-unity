// 选项池：键用「块类型.字段名」，不能只用字段名。
function 收集选项() {
  const 池 = {};
  for (const [类型, 定义] of Object.entries(块定义)) {
    for (const f of 定义.字段 || []) {
      if (!f.选项) continue;
      池[类型 + '.' + f.k] = f.选项;
    }
  }
  return 池;
}

// 按分组归类，给侧边栏用
function 按组归类() {
  const 组 = {};
  for (const 名 of 分组顺序) 组[名] = [];
  for (const [类型, 定义] of Object.entries(块定义)) {
    const g = 定义.组 || '杂项';
    (组[g] = 组[g] || []).push(类型);
  }
  return 组;
}

// 新建一个块：字段直接填上通用默认值
function 新块(类型) {
  const 定义 = 块定义[类型];
  const b = { 类型, 子: [] };
  (定义.字段 || []).forEach(f => { b[f.k] = f.默认 ?? ''; });
  return b;
}

// 块树 → 中文套式源码（保留嵌套缩进）
function 生成中文(块树) {
  const 行 = [];

  const 有类 = 块树.some(b => b.类型 === '类');
  const 已写使用 = 块树.some(b => b.类型 === '使用');

  // 某些块必须在文件头上补 using，不然编译不过 —— 与其让人记，不如自动加
  const 用到 = (类型名) => {
    let 有 = false;
    (function 找(列表) {
      for (const b of 列表) {
        if (b.类型 === 类型名) 有 = true;
        找(b.子 || []);
        for (const 段 of b.分支 || []) 找(段.子 || []);
      }
    })(块树);
    return 有;
  };

  const 头 = [];
  if (有类 && !已写使用) 头.push('使用 UnityEngine');
  if (用到('切换场景')) 头.push('使用 UnityEngine.SceneManagement');
  if (用到('改文字')) 头.push('使用 UnityEngine.UI');
  if (头.length) 行.push(...头, '');

  const 走 = (块们, 深, 父) => {
    for (const b of 块们) {
      const 定义 = 块定义[b.类型];
      if (!定义) continue;

      const 缩进 = '    '.repeat(深);
      for (const 行内容 of 定义.模板(b)) 行.push(缩进 + 行内容);

      if (定义.可容纳) {
        行.push(缩进 + '{');
        走(b.子 || [], 深 + 1, b);

        // C# 要求每个 case 能以 break/return 脱离开关，否则 CS8070
        if (父 && 父.类型 === '多分支' && (b.类型 === '遇' || b.类型 === '其他')) {
          const 最后 = (b.子 || []).slice(-1)[0];
          if (!最后 || (最后.类型 !== '跳出' && 最后.类型 !== '返回')) {
            行.push('    '.repeat(深 + 1) + '跳出');
          }
        }

        行.push(缩进 + '}');
      }
    }
  };

  走(块树, 0, null);
  return 行.join('\n');
}

// 块树 → 中文 → C#
function 生成CSharp(块树) {
  const 中文 = 生成中文(块树);
  const 译 = (typeof window !== 'undefined' && window.Zh2Unity)
    ? window.Zh2Unity.译脚本
    : require('./zh2unity.js').译脚本;
  return 译(中文);
}

