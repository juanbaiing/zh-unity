// 块树 → 中文 → C# 的端到端测试
const { 新块, 生成中文, 生成CSharp } = require('./blocks.js');
const fs = require('fs');
const path = require('path');

// 用代码搭出用户画的那张图的块树
const 类 = 新块('类');
类.名 = '敌人';
类.继承 = 'MonoBehaviour';

const 血量 = 新块('字段'); 血量.数据类型 = '整数'; 血量.名 = '血量'; 血量.值 = '30';
const 分   = 新块('字段'); 分.数据类型   = '整数'; 分.名   = '分';   分.值   = '10';
const 目标 = 新块('字段'); 目标.数据类型 = '变换'; 目标.名 = '目标';

const 开始 = 新块('方法'); 开始.名 = '开始时'; 开始.公开 = false;
const 打印1 = 新块('打印'); 打印1.值 = '"敌人已生成"';
开始.子.push(打印1);

const 受伤 = 新块('方法'); 受伤.名 = '受伤'; 受伤.参数 = '整数 伤害'; 受伤.公开 = true;
const 减血 = 新块('赋值'); 减血.左 = '血量'; 减血.右 = '血量 - 伤害';
const 打印2 = 新块('打印'); 打印2.值 = '"血量：" + 血量';
const 判断 = 新块('设若'); 判断.条件 = '血量 小于等于 0';
const 调用死亡 = 新块('调用'); 调用死亡.名 = '死亡';
判断.子.push(调用死亡);
受伤.子.push(减血, 打印2, 判断);

const 死亡 = 新块('方法'); 死亡.名 = '死亡'; 死亡.公开 = false;
const 打印3 = 新块('打印'); 打印3.值 = '"死亡，得分 +" + 分';
const 判断2 = 新块('设若'); 判断2.条件 = '目标 不等于 空';
const 归零 = 新块('赋值'); 归零.左 = '目标.位置'; 归零.右 = '新向量（0, 0, 0）';
判断2.子.push(归零);
const 销毁 = 新块('调用'); 销毁.名 = '销毁'; 销毁.参数 = '自己，1';
死亡.子.push(打印3, 判断2, 销毁);

类.子.push(血量, 分, 目标, 开始, 受伤, 死亡);

const 中文 = 生成中文([类]);
const CSharp = 生成CSharp([类]);

console.log('=== 块树 → 中文 ===');
console.log(中文);

console.log('\n=== 块树 → C# ===');
console.log(CSharp);

// 写进编译验证项目
fs.writeFileSync(path.join(__dirname, 'unitycheck', '敌人.cs'), CSharp, 'utf8');
console.log('已写入 unitycheck/敌人.cs');
