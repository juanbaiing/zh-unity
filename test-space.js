// 空间模型测试：块的父子全靠几何推导，看拖到哪就生成成什么样
const { 推导, 生成, 生成CSharp, 找孤岛 } = require('./space.js');

// 块只有坐标和图层（x/y 是画布上的位置，生成时按它排前后）
const 块们 = [
  { id: 1, 类型: '类',    z: 0, x: 0,   y: 0,   字段: { 名: '敌人', 继承: 'MonoBehaviour' } },
  { id: 2, 类型: '方法',  z: 1, x: 20,  y: 60,  字段: { 名: '更新时', 参数: '' } },
  { id: 3, 类型: '设若',  z: 2, x: 40,  y: 120, 字段: { 条件: '血量 小于等于 0' } },
  { id: 4, 类型: '打印',  z: 3, x: 60,  y: 170, 字段: { 值: '"死了"' } },
  { id: 5, 类型: '字段',  z: 1, x: 30,  y: 30,  字段: { 数据类型: '整数', 名: '血量', 值: '30' } },
  { id: 6, 类型: '打印',  z: 1, x: 800, y: 700, 字段: { 值: '"飘在外面"' } },   // 故意放在盒子外
];

// 矩形：类 0-600 x 0-500，方法在类里，设若在方法里，打印在设若里
const 矩形 = new Map([
  [1, { x: 0,   y: 0,   w: 600, h: 500 }],   // 类
  [2, { x: 20,  y: 60,  w: 540, h: 400 }],   // 方法（在类里）
  [3, { x: 40,  y: 120, w: 480, h: 260 }],   // 设若（在方法里）
  [4, { x: 60,  y: 170, w: 200, h: 30 }],    // 打印（在设若里）
  [5, { x: 30,  y: 30,  w: 200, h: 26 }],    // 字段（在类里，不在方法里）
  [6, { x: 800, y: 700, w: 200, h: 26 }],    // 打印（盒子外）
]);

const 父表 = 推导(块们, 矩形);
console.log('=== 推导出的父子 ===');
for (const b of 块们) {
  console.log(`  ${b.id} ${b.类型}  →  父 ${父表.get(b.id) ?? '（无，在画布上）'}`);
}

console.log('\n=== 孤岛（没进任何盒子、也不是类）===');
找孤岛(块们, 父表).forEach(b => console.log(`  ${b.类型}：${JSON.stringify(b.字段)}`));

console.log('\n=== 生成的中文 ===');
console.log(生成(块们, 父表));

console.log('\n=== 生成的 C# ===');
console.log(生成CSharp(块们, 父表));
