const { 生成中文, 找孤岛 } = require('./canvas.js');

// 块表：id -> 块。内容字段扁平存在块上（和块定义模板一致）
// 父 = 所属容器；后 = 同容器内下一个；x/y = 画布坐标
const 表 = new Map();

function 加(id, 类型, 内容, 父, 后, x) {
  表.set(id, { ...内容, id, 类型, x: x ?? id * 10, y: 0, 父: 父 ?? null, 后: 后 ?? null });
}

加(1, '类', { 名: '敌人', 继承: 'MonoBehaviour' });
加(2, '字段', { 数据类型: '整数', 名: '血量', 值: '30' }, 1, 3, 10);
加(3, '字段', { 数据类型: '整数', 名: '分', 值: '10' }, 1, 4, 20);
加(4, '方法', { 名: '开始时', 参数: '' }, 1, 5, 30);
加(5, '方法', { 名: '受伤', 参数: '整数 伤害' }, 1, null, 40);

// 方法「开始时」里挂一句打印
加(6, '打印', { 值: '"敌人已生成"' }, 4, null, 10);

// 孤岛 A：没父的字段
加(7, '字段', { 数据类型: '整数', 名: '孤儿', 值: '1' }, null, null, 50);
// 孤岛 B：在类里但没连上主链（是另一个链头）
加(8, '打印', { 值: '"没连上"' }, 1, null, 60);

console.log('=== 生成中文 ===');
console.log(生成中文(表));

console.log('\n=== 孤岛 ===');
const 孤 = 找孤岛(表);
if (!孤.length) console.log('（没有孤岛）');
for (const { 块, 原因 } of 孤) {
  console.log(`  id=${块.id} ${块.类型}「${块.名 || 块.值 || ''}」 — ${原因}`);
}
