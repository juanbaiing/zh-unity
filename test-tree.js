// 树模型端到端测试：搭类 → 方法 → if 链 → 循环 → 容器，再编译
const { 新, 加分支, 生成, 生成CSharp } = require('./blocks2.js');
const fs = require('fs');
const path = require('path');

// ---- 类 ----
const 类 = 新('类', { 名: '玩家', 继承: 'MonoBehaviour' });

// 字段
类.子.push(新('字段', { 数据类型: '整数', 名: '血量', 值: '100' }));
类.子.push(新('字段', { 数据类型: '整数列表', 名: '队伍', 值: '' }));

// 方法：开始时
const 开始 = 新('方法', { 名: '开始时', 参数: '' });
开始.子.push(新('打印', { 值: '"开始"' }));
类.子.push(开始);

// 方法：更新时 —— 里面放一条 if 链（一块，内部分支）
const 更新 = 新('方法', { 名: '更新时', 参数: '' });

const 设若 = 新('设若', { 条件: '血量 小于等于 0' });
设若.子.push(新('打印', { 值: '"死了"' }));

// 加「否则若」分支
const 否则若 = 加分支(设若, { 条件: '血量 小于 30' });
否则若.子.push(新('打印', { 值: '"危险"' }));

// 加「否则」分支
const 否则 = 加分支(设若, {}, true);
否则.子.push(新('打印', { 值: '"安全"' }));

更新.子.push(设若);
更新.子.push(新('改变量', { 名: '血量', 运算法: '减一', 值: '' }));
类.子.push(更新);

// 方法：重置 —— 里面放一个循环
const 重置 = 新('方法', { 名: '重置', 参数: '', 公开: true });
const 重复 = 新('重复', { 次数: '3' });
重复.子.push(新('添加', { 名: '队伍', 值: '1' }));
重置.子.push(重复);
重置.子.push(新('清空', { 名: '队伍' }));
类.子.push(重置);

const 中文 = 生成([类]);
const CSharp = 生成CSharp([类]);

console.log('=== 中文 ===');
console.log(中文);
console.log('\n=== C# ===');
console.log(CSharp);

fs.writeFileSync(path.join(__dirname, 'unitycheck', '敌人.cs'), CSharp, 'utf8');
console.log('已写入 unitycheck/敌人.cs');
